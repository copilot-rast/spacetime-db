import { gameInit } from './game/init';

function seedAll(ctx: unknown) {
  seedBase(ctx as never);
  seedPlayers(ctx as never);
  seedEconomy(ctx as never);
  seedGamification(ctx as never);
  seedItems(ctx as never);
  seedPromo(ctx as never);
  seedPublication(ctx as never);
  seedSocial(ctx as never);
}

export const init = spacetimedb.init(ctx => {
  seedAll(ctx);
  gameInit(ctx);
});

export const onConnect = spacetimedb.clientConnected(ctx => {
  seedAll(ctx);
});

