  await save(page, 'sr-dialog');
  await expect(row).toContainText('توکن ثابت');

  await open(page, 'news?status=pending_review');
  await waitFor(() => [...owner.conn.db.adminNews.iter()].some(n => n.externalKey && n.title.some(x => x.text === `خبر وب‌هوک ${S}`)), 5000);
